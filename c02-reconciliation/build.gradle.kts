// c02-reconciliation —— 聚合目录，自身不产出代码，只作三个子模块的父路径。
//
// 为什么要拆三个子模块：这一篇讲的是「三方各自持账、互相看不见，所以要靠对账」。
// 单模块时代这个边界只存在于 @Profile 注解和口头约定里——三个进程跑同一个 jar，
// JPA 按包扫描实体，结果每个库都把三方的表建全了，所谓「隔离」只是数据没写错而已。
//
// 拆成模块后，边界升级为编译期约束：
//   bank 的 classpath 里根本没有 SettlementService，想跨进程直连也编译不过。
//
// 模块边界 = 进程边界（子目录不带 c02- 前缀，避免 IDEA 模块名里 c02 出现两次）：
//   shared      库，不可独立启动（领域词汇 + 两份跨进程契约 + MQ 拓扑）
//   bank        可执行，同一份代码起两次 → 工行 :18081 / 建行 :18082
//   settlement  可执行，结算服务 + 对账 Job 同进程 → :18080
//
// 银行侧不再细分 icbc/ccb 两个模块：它们是同一角色的两个实例，代码完全相同，
// 只有配置里的银行代码和库名不同。为「实例」建模块只会多一层纯技术中间层。
//
// group / version / repositories 由根 build.gradle.kts 的 allprojects{} 统一下发。
